#!/usr/bin/env python3
"""The forward gate: every NEW config key reaches every required surface.

    python3 scripts/audit-config-keys.py --check
    python3 scripts/audit-config-keys.py            # report only
    python3 scripts/audit-config-keys.py --list-legacy   # print the inventory

WHY THIS EXISTS (the plan's own words)
======================================
`docs/plans/2026-11-14-config-resilience-architecture-...` §5 measured what
forces a new config key through the whole surface. The answer was: nothing.

  the compiler                     forces the struct field, and nothing else
  tests/example_template_loads.rs   REVERSE only (a template key the binary
                                    does not know fails; a struct key the
                                    template OMITS is invisible)
  scripts/audit-config-surface.py   forward, but only for keys with NO reader
  scripts/check-doc-claims.sh       AGENTS.md claims only
  genome lint                       doc hygiene, nothing about keys

So an agent could add a key that compiles, passes every gate, and is invisible
to the operator (no template line), to the doctor (no row), to the heal contract
(no entry) and to the describe surface (none). This script closes that.

WHY A BASELINE AND NOT A WALL OF RED
====================================
The tree has 272 config keys and 117 of them predate the note discipline. A gate
that fails all 762 missing touch-points is a gate nobody can land anything
through — the `audit-config-surface.py` note above says exactly that about its
own always-red `--check`: "a check that is always red carries no information."

So the gate is a RATCHET. `LEGACY` names every key that already existed when the
gate landed, with the count of surfaces it misses. The check is:

  * a key NOT in LEGACY that misses ANY surface → FAIL, one row per surface;
  * a key IN LEGACY that now misses MORE surfaces than recorded → FAIL
    (the ratchet only moves forward);
  * a key IN LEGACY that now misses FEWER → PASS, and the entry is reported as
    stale so the baseline shrinks as the tree improves;
  * a key IN LEGACY that no longer exists → reported stale, so the baseline
    cannot grow a graveyard.

That is the same shape as `ACCOUNTED_FOR` in audit-config-surface.py, and it
makes the baseline honest: it can only shrink.

THE SURFACES
============
  1. the note      — the doc comment, which the registry already carries.
  2. the heal entry — config_heal.rs names the key, OR the key is in
                      NO_HEAL_NEEDED with a reason.
  3. the template   — operant.example.toml names the key (commented counts).
  4. the doctor row — doctor.rs's config sweep can report it, OR the key is in
                      NO_DOCTOR with a reason.
  5. the describe output — generated from the registry, so it is satisfied by
                     construction. The gate asserts the registry is non-empty,
                     because an empty registry would make every other check
                     vacuously pass.

Usage: python3 scripts/audit-config-keys.py [--check] [--list-legacy]
Exit: 0 when the ratchet holds; 1 when a new key misses a surface, or a legacy
      key got worse.
"""

